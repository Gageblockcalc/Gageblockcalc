#!/bin/bash
# Writes version.js for the footer label "v1.0.<n> · <commit> · <date>" (1.0 matches the Expo app's version).
# Run right before the release commit: ./scripts/write-version.sh 1.0.134
# Without an argument, <n> = commits on this branch + 1. That count has run ahead of the
# published stamp, so a release passes the stamp explicitly. <commit> = HEAD when the script runs.
set -euo pipefail
cd "$(dirname "$0")/.."
BASE=1.0
N=$(( $(git rev-list --count HEAD) + 1 ))
# The commit count has run ahead of the published stamp (v1.0.133 is live).
# A release passes the stamp: ./scripts/write-version.sh 1.0.134
REQ="${1:-}"
if [[ -n "$REQ" ]]; then
  if [[ ! "$REQ" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "version must look like 1.0.134" >&2
    exit 1
  fi
  VER="$REQ"
else
  VER="$BASE.$N"
fi
SHA=$(git rev-parse --short HEAD)
DATE=$(TZ=America/New_York date +%Y-%m-%d)
cat > version.js <<JS
// Generated by scripts/write-version.sh, do not edit.
window.CALC_VERSION={version:"$VER",commit:"$SHA",date:"$DATE"};
(function(){function s(){var e=document.getElementById('calcVersion');if(e)e.textContent='v'+window.CALC_VERSION.version+' \u00b7 '+window.CALC_VERSION.commit+' \u00b7 '+window.CALC_VERSION.date;}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',s);else s();})();
JS
# Cache-bust every local script/CSS/worker/SW URL with ?v=<version>.
python3 scripts/stamp-assets.py "$VER"
# Bump the service worker cache with every release so returning visitors drop old files.
sed -i -E "s/^const CACHE = '[^']*';/const CACHE = 'gbc-$VER';/" sw.js
# Server-render the label into index.html's static HTML (version.js may still refresh it).
sed -i -E "s#(<span id=\"calcVersion\"[^>]*>)[^<]*(</span>)#\1v$VER · $SHA · $DATE\2#" index.html
echo "version.js: v$VER · $SHA · $DATE"
